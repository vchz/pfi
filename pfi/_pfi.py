"""Composite PFI estimator and estimator factory helpers."""

import numpy as np

from sklearn.base import BaseEstimator, clone
from sklearn.base import _fit_context as fit_context
from sklearn.utils.validation import check_is_fitted
from sklearn.utils._param_validation import HasMethods
from sklearn_compat.utils.validation import validate_data
from .flow import FlowEstimator
from .score import ScoreEstimator

class PFI(BaseEstimator):
    """Composite estimator that fits score first and flow second.

    Parameters
    ----------
    score_estimator : ScoreEstimator
        Score-stage estimator.
    flow_estimator : FlowEstimator
        Flow-stage estimator.
    fit_on_score_samples : bool, default=False
        If ``True``, fit the flow stage on samples generated by the fitted
        score estimator rather than on the original training data.

    Attributes
    ----------
    score_estimator_ : ScoreEstimator
        Fitted score-stage estimator.
    flow_estimator_ : FlowEstimator
        Fitted flow-stage estimator.

    """

    _parameter_constraints = {
        "score_estimator": [HasMethods(["fit", "predict", "sample", "score"]), None],
        "flow_estimator": [HasMethods(["fit", "predict", "sample", "score"]), None],
    }

    def __init__(
        self,
        score_estimator=None,
        flow_estimator=None,
    ):
        self.score_estimator = score_estimator
        self.flow_estimator = flow_estimator

    def _more_tags(self):
        return {"non_deterministic": True, "multioutput_only": True}
    
    def __sklearn_tags__(self):
        tags = super().__sklearn_tags__()
        tags.non_deterministic = True
        tags.target_tags.multi_output = True
        return tags

    def __sklearn_is_fitted__(self):
        """Return whether the composite estimator has been fitted."""
        return hasattr(self, "score_estimator_") and hasattr(self, "flow_estimator_")

    @fit_context(prefer_skip_nested_validation=True)
    def fit(self, X, y=None):
        """Fit the score estimator, then the flow estimator.

        Parameters
        ----------
        X : array-like of shape (n_samples, ndim + 1)
            Training data with time stored in the last column.
        y : None, default=None
            Ignored. Present for future compatibility with sklearn.

        Returns
        -------
        PFI
            Fitted estimator.
        """
        _ = y
        X = validate_data(self, X, reset=True, ensure_2d=True, dtype="numeric")
        score_est = self.score_estimator if self.score_estimator is not None else ScoreEstimator()
        flow_est = self.flow_estimator if self.flow_estimator is not None else FlowEstimator()
        self.score_estimator_ = clone(score_est)
        self.flow_estimator_ = clone(flow_est)

        self.score_estimator_.fit(X)
        if getattr(self.flow_estimator_, "flow", None) is not None and hasattr(self.flow_estimator_.flow, "score"):
            self.flow_estimator_.flow.score = self.score_estimator_.model_

        self.flow_estimator_.fit(X)
        return self

    def predict(self, X, stoch=False):
        """Predict flow values using the fitted flow estimator.

        Parameters
        ----------
        X : array-like of shape (n_samples, ndim + 1)
            Input states with time in the last column.
        stoch : bool, default=False
            Whether to request stochastic output.

        Returns
        -------
        ndarray
            Predicted flow values.
        """
        check_is_fitted(self, ["score_estimator_", "flow_estimator_"])
        X = validate_data(self, X, reset=False, ensure_2d=True, dtype="numeric")
        return self.flow_estimator_.predict(X, stoch=stoch)

    def sample(self, X, Dt, dt=0.01, stoch=False):
        """Sample trajectories with the fitted flow estimator.

        Parameters
        ----------
        X : array-like of shape (n_samples, ndim + 1)
            Initial states with time in the last column.
        Dt : float
            Simulation horizon.
        dt : float, default=0.01
            Integration step.
        stoch : bool, default=False
            Whether to use stochastic dynamics.

        Returns
        -------
        ndarray
            Simulated final states.
        """
        check_is_fitted(self, ["score_estimator_", "flow_estimator_"])
        X = validate_data(self, X, reset=False, ensure_2d=True, dtype="numeric")
        return self.flow_estimator_.sample(X, Dt=Dt, dt=dt, stoch=stoch)

    def error(self, X, y, dt=0.01, stoch=False):
        """Compute flow-stage evaluation errors.

        Parameters
        ----------
        X : array-like of shape (n_samples_x, ndim + 1)
            Source samples with time in the last column.
        y : array-like of shape (n_samples_y, ndim + 1)
            Target samples with time in the last column.
        dt : float, default=0.01
            Integration step used during flow simulation.
        stoch : bool, default=False
            Whether to use stochastic dynamics.

        Returns
        -------
        ndarray
            Per-time energy-distance scores.
        """
        check_is_fitted(self, ["score_estimator_", "flow_estimator_"])
        X = validate_data(self, X, reset=False, ensure_2d=True, dtype="numeric")
        return self.flow_estimator_.error(X, y, dt=dt, stoch=stoch)

    def score(self, X, y, dt=0.01, stoch=False):
        """Return the negated mean error for sklearn compatibility.

        Parameters
        ----------
        X : array-like of shape (n_samples_x, ndim + 1)
            Source samples with time in the last column.
        y : array-like of shape (n_samples_y, ndim + 1)
            Target samples with time in the last column.
        dt : float, default=0.01
            Integration step used during flow simulation.
        stoch : bool, default=False
            Whether to use stochastic dynamics.

        Returns
        -------
        float
            Negated mean error. Larger values indicate better fit.
        """
        errors = self.error(X, y, dt=dt, stoch=stoch)
        if errors.size == 0:
            return float("nan")
        return -float(np.mean(errors))

def make_pfi_estimator(
    score_model=None,
    flow_model=None,
    growth_model=None,
    s_solver="dsm",
    f_solver="pfm",
    s_solver_kwargs=None,
    f_solver_kwargs=None,
    device="cpu",
    random_state=0,
):
    """Create a configured composite ``PFI`` estimator.

    Parameters
    ----------
    score_model : torch.nn.Module or None, default=None
        Score model. If ``None``, a default ``DSMScore`` is used.
    flow_model : torch.nn.Module or None, default=None
        Flow model. If ``None``, a default ``CLEFlow`` is used.
    growth_model : torch.nn.Module or None, default=None
        Optional growth model for unbalanced solvers.
    s_solver : str, default='dsm'
        Score solver name.
    f_solver : str, default='pfm'
        Flow solver name.
    s_solver_kwargs : dict or None, default=None
        Keyword arguments forwarded to the score solver.
    f_solver_kwargs : dict or None, default=None
        Keyword arguments forwarded to the flow solver.
    device : str or torch.device, default='cpu'
        Device used for both estimators.
    random_state : int, RandomState or None, default=0
        Random state for both estimators.

    Returns
    -------
    PFI
        Configured composite estimator.
    """
    s_kw = {} if s_solver_kwargs is None else dict(s_solver_kwargs)
    s_kw.setdefault("verbose", False)
    f_kw = {} if f_solver_kwargs is None else dict(f_solver_kwargs)
    f_kw.setdefault("verbose", False)

    score_estimator = ScoreEstimator(
        model=score_model,
        solver=s_solver,
        solver_kwargs=s_kw,
        device=device,
        random_state=random_state,
    )
    flow_estimator = FlowEstimator(
        flow=flow_model,
        growth=growth_model,
        solver=f_solver,
        solver_kwargs=f_kw,
        device=device,
        random_state=random_state,
    )
    return PFI(
        score_estimator=score_estimator,
        flow_estimator=flow_estimator,
    )

